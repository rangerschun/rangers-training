export const RUNNING_WEEKS=Object.freeze([1,2,3,4,5,6]);
export const runningToday=(date=new Date())=>new Intl.DateTimeFormat('en-CA',{timeZone:'America/Toronto',year:'numeric',month:'2-digit',day:'2-digit'}).format(date);
export function runningSource(week,day){if(!Number.isInteger(week)||week<1||week>6||!Number.isInteger(day)||day<1||day>4)throw Error('Choose a valid running week and training day.');return `driveline-running-w${week}-d${day}`;}
export function runningDay(week,day){
 runningSource(week,day);const source=RUNNING_DAYS[day-1];return {...source,rows:source.rows.map((r,i)=>{
  const late=week>=4&&r.late,url=late?r.lateurl:r.url,related=Boolean(late&&!url&&r.url),link=url??(related?r.url:null);
  if(link&&!/^https:\/\/(?:vimeo\.com|player\.vimeo\.com)\//.test(link))throw Error('The source demonstration link is invalid.');
  return {id:`run-w${week}-d${day}-e${i+1}`,name:late?r.late:r.name,dose:r.dose[week-1].replaceAll('×','x'),rest:r.rest,url:link,related,note:late&&r.note?r.note:''};
 })};
}
export function runningNotes(record){return (record?.notes??'').replace(/^Running progress: [^\n]*\n?/,'');}
export function runningRecord({player,week,day,date,notes='',checked,previous,now=new Date()}){
 const source=runningSource(week,day),plan=runningDay(week,day),stamp=now.toISOString();
 if(typeof player!=='string'||!player.trim())throw Error('Choose a player.');
 if(typeof date!=='string'||!/^\d{4}-\d{2}-\d{2}$/.test(date)||!Number.isFinite(Date.parse(date+'T12:00:00Z'))||new Date(date+'T12:00:00Z').toISOString().slice(0,10)!==date||date>runningToday(now))throw Error('Choose today or an earlier workout date.');
 if(typeof notes!=='string'||notes.length>400)throw Error('Keep day notes within 400 characters.');
 if(!Array.isArray(checked)||checked.length!==plan.rows.length||checked.some(v=>typeof v!=='boolean')||!checked.some(Boolean))throw Error('Check at least one exercise you completed before saving.');
 if(previous&&(previous.player!==player||previous.source_template_id!==source))throw Error('This saved day belongs to another player or plan.');
 const done=checked.filter(Boolean).length;
 return {id:previous?.id??`running-${player}-w${week}-d${day}`,player,session_date:date,title:`Driveline Running · Week ${week} / ${plan.day}`,category:'speed',duration_minutes:null,effort:'',notes:`Running progress: ${done} / ${checked.length} planned exercises completed.${done<checked.length?' Remaining exercises not completed.':''}\n${notes.trim()}`.trim(),source_template_id:source,completion_status:done===checked.length?'completed':'partial',completion_confirmed:true,created_at:previous?.created_at??stamp,updated_at:stamp,exercises:plan.rows.map((r,i)=>({name:r.name,sets:null,reps:null,weight:null,weight_unit:'none',notes:checked[i]?`Completed ${r.dose}. Rest ${r.rest}.`:'',completed:checked[i],source_exercise_id:r.id,planned_details:`${r.dose} · Rest ${r.rest}${r.note?' · '+r.note:''}`}))};
}
export function runningProgress(records,player){
 const weeks=RUNNING_WEEKS.map(w=>{let n=0;for(let d=1;d<=4;d++){const r=records.filter(r=>r.player===player&&r.source_template_id===runningSource(w,d)).sort((a,b)=>String(b.updated_at??'').localeCompare(String(a.updated_at??'')))[0];if(r?.completion_status==='completed'&&r.exercises?.length===runningDay(w,d).rows.length&&r.exercises.every(e=>e.completed===true))n++;}return n;});return {weeks,completed:weeks.reduce((a,b)=>a+b,0)};
}
