export const RUNNING_PROGRAMS=Object.freeze({driveline:'Driveline Running','ota-bodyweight':'OTA Body Weight','ota-beginner':'OTA Speed Agility Beginner','ota-advanced':'OTA Speed Agility Advanced'});
export function runningProgramFromHash(hash){const p=String(hash??'').replace(/^#/,'').split('/');return p[0]==='running'&&Object.hasOwn(RUNNING_PROGRAMS,p[1])?p[1]:'driveline';}
export function otaSource(program,week,day){
 if(program==='ota-beginner'){if(!Number.isInteger(week)||week<1||week>12||!Number.isInteger(day)||day<1||day>4)throw Error('Choose a valid Beginner week and day.');return `ota-beginner-w${week}-d${day}`;}
 if(program==='ota-bodyweight'||program==='ota-advanced')return `${program}-reference`;
 throw Error('Choose an OTA running program.');
}
export function otaSession(program,week,day){
 otaSource(program,week,day);
 if(program==='ota-beginner')return OTA_BEGINNER_SESSIONS.find(s=>s.week===week&&s.day===day);
 return program==='ota-bodyweight'?{title:'Bodyweight · Phase 1, day 2',details:'1 x 300-yard shuttle\nTurn every 25 yards.'}:{title:'Advanced · Phase 1, week 1, day 4',details:'6 x 50-yard build-up sprints'};
}
export function otaRecordProgram(record){const s=record?.source_template_id??'';if(/^ota-beginner-w(?:[1-9]|1[0-2])-d[1-4]$/.test(s))return 'ota-beginner';return s==='ota-bodyweight-reference'?'ota-bodyweight':s==='ota-advanced-reference'?'ota-advanced':null;}
export function otaComplete(record){return Boolean(otaRecordProgram(record)&&record.completion_status==='completed'&&record.completion_confirmed===true&&record.exercises?.length===1&&record.exercises[0].source_exercise_id===record.source_template_id&&record.exercises[0].completed===true);}
export function otaBeginnerProgress(records,player){
 const weeks=Array.from({length:12},(_,i)=>{let n=0;for(let d=1;d<=4;d++){const r=records.filter(r=>r.player===player&&r.source_template_id===otaSource('ota-beginner',i+1,d)).sort((a,b)=>String(b.updated_at??'').localeCompare(String(a.updated_at??'')))[0];if(otaComplete(r))n++;}return n;});return {weeks,completed:weeks.reduce((a,b)=>a+b,0)};
}
export function otaUserNotes(record){return (record?.notes??'').replace(/^OTA session completed\.\n?/,'');}
export function otaWorkoutRecord({program,player,week,day,date,notes='',completed,previous,records=[],now=new Date()}){
 const source=otaSource(program,week,day),session=otaSession(program,week,day),stamp=now.toISOString();
 if(typeof player!=='string'||!player.trim())throw Error('Choose a player.');
 if(typeof date!=='string'||!/^\d{4}-\d{2}-\d{2}$/.test(date)||!Number.isFinite(Date.parse(date+'T12:00:00Z'))||new Date(date+'T12:00:00Z').toISOString().slice(0,10)!==date||date>runningToday(now))throw Error('Choose today or an earlier workout date.');
 if(typeof notes!=='string'||notes.length>400)throw Error('Keep day notes within 400 characters.');
 if(completed!==true)throw Error('Complete all listed work and check the completion box before saving.');
 if(program==='ota-advanced'&&otaBeginnerProgress(records,player).completed<48)throw Error('Finish all 48 Beginner sessions before starting Advanced.');
 if(previous&&(previous.player!==player||previous.source_template_id!==source||(program!=='ota-beginner'&&previous.session_date!==date)))throw Error('This saved session belongs to another player or plan.');
 return {id:previous?.id??`${source}-${player}${program==='ota-beginner'?'':'-'+date}`,player,session_date:date,title:`${RUNNING_PROGRAMS[program]} · ${program==='ota-beginner'?`Week ${week} / Day ${day}`:'Reference workout'}`,category:'speed',duration_minutes:null,effort:'',notes:`OTA session completed.\n${notes.trim()}`.trim(),source_template_id:source,completion_status:'completed',completion_confirmed:true,created_at:previous?.created_at??stamp,updated_at:stamp,exercises:[{name:session.title,sets:null,reps:null,weight:null,weight_unit:'none',notes:'Completed all listed work.',completed:true,source_exercise_id:source,planned_details:session.details}]};
}
